CREATE TABLE IF NOT EXISTS departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    ai_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ai_instructions TEXT NOT NULL DEFAULT '',
    ai_additional_context TEXT NOT NULL DEFAULT ''
);

ALTER TABLE departments
    ADD COLUMN IF NOT EXISTS ai_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS ai_instructions TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS ai_additional_context TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    role_job TEXT,
    phone TEXT NOT NULL,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS agents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    department_id INTEGER REFERENCES departments (id),
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers (id),
    department_id INTEGER NOT NULL REFERENCES departments (id),
    assigned_agent_id INTEGER REFERENCES agents (id),
    ai_handoff BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING'
        CHECK (status IN ('WAITING', 'IN_PROGRESS', 'CLOSED')),
    access_token_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE tickets
    ADD COLUMN IF NOT EXISTS access_token_hash VARCHAR(64),
    ADD COLUMN IF NOT EXISTS ai_handoff BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets (id),
    sender_type VARCHAR(20) NOT NULL CHECK (sender_type IN ('CUSTOMER', 'AGENT', 'BOT')),
    sender_id INTEGER,
    message_text TEXT NOT NULL DEFAULT '',
    attachment_name TEXT,
    attachment_type TEXT,
    attachment_data TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_sender_type_check;
ALTER TABLE messages
    ADD CONSTRAINT messages_sender_type_check
    CHECK (sender_type IN ('CUSTOMER', 'AGENT', 'BOT'));

CREATE INDEX IF NOT EXISTS idx_agents_department_id ON agents (department_id);
CREATE INDEX IF NOT EXISTS idx_tickets_status ON tickets (status);
CREATE INDEX IF NOT EXISTS idx_tickets_department_id ON tickets (department_id);
CREATE INDEX IF NOT EXISTS idx_tickets_assigned_agent_id ON tickets (assigned_agent_id);
CREATE INDEX IF NOT EXISTS idx_messages_ticket_created ON messages (ticket_id, created_at, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tickets_access_token_hash
    ON tickets (access_token_hash)
    WHERE access_token_hash IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_departments_name_case_insensitive
    ON departments (LOWER(name));

