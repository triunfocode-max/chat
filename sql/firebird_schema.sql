CREATE TABLE DEPARTMENTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(150) NOT NULL UNIQUE,
    AI_ENABLED SMALLINT DEFAULT 0 NOT NULL CHECK (AI_ENABLED IN (0, 1)),
    AI_INSTRUCTIONS VARCHAR(4000) DEFAULT '' NOT NULL
);

CREATE TABLE CUSTOMERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR(150) NOT NULL,
    ROLE_JOB VARCHAR(150),
    PHONE VARCHAR(20) NOT NULL,
    IS_VERIFIED SMALLINT DEFAULT 0 NOT NULL CHECK (IS_VERIFIED IN (0, 1)),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE AGENTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    DEPARTMENT_ID BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_AGENTS_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID)
);

CREATE TABLE TICKETS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID BIGINT NOT NULL,
    DEPARTMENT_ID BIGINT NOT NULL,
    ASSIGNED_AGENT_ID BIGINT,
    AI_HANDOFF SMALLINT DEFAULT 0 NOT NULL CHECK (AI_HANDOFF IN (0, 1)),
    STATUS VARCHAR(20) DEFAULT 'WAITING' NOT NULL CHECK (STATUS IN ('WAITING', 'IN_PROGRESS', 'CLOSED')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TICKETS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (ID),
    CONSTRAINT FK_TICKETS_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID),
    CONSTRAINT FK_TICKETS_AGENT FOREIGN KEY (ASSIGNED_AGENT_ID) REFERENCES AGENTS (ID)
);

CREATE TABLE MESSAGES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TICKET_ID BIGINT NOT NULL,
    SENDER_TYPE VARCHAR(20) NOT NULL CHECK (SENDER_TYPE IN ('CUSTOMER', 'AGENT')),
    SENDER_ID BIGINT,
    MESSAGE_TEXT BLOB SUB_TYPE TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_MESSAGES_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKETS (ID)
);

CREATE INDEX IDX_DEPARTMENTS_NAME ON DEPARTMENTS (NAME);
CREATE INDEX IDX_CUSTOMERS_PHONE ON CUSTOMERS (PHONE);
